// Rows "Position n" + "k factor" for a list of [config, camera] columns.
export function positionRows(posLabel, kLabel, cols) {
  const rows = [0, 1, 2, 3, 4].map(i => [`${posLabel} ${i + 1}`, ...cols.map(([c, cam]) => ballBar[c][cam][i])])
  rows.push([kLabel, ...cols.map(([c, cam]) => ballBar[c].k[cam === 'cam1' ? 0 : 1])])
  return rows
}

